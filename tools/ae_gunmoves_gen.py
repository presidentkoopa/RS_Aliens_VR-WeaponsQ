"""AE: generate zscript/rsq/gunmoves.zs the way kit/team/hands_work/rsq_gunmoves_gen.py does for BD22
(same maths, copied: Pivot / Mirrored / Blends per gun, and per (sprite, frame) the body's turn and
move off the ready frame in the hand models' frame). Every keyed frame of the gun's own mesh that
moves the body is listed (fire, pump, the set's own reload swings), not only the fire frames.
usage: ae_gunmoves_gen.py <AE dir> <out.zs>"""
import sys, os, math, glob, json
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kick_measure as km
D = np.diag([-1.0, 1.0, 1.0])
O_H = np.array([0.0, -10.0, -24.0])
MIN_MOVE, MIN_TURN = 0.3, 0.4
def rot_y(a):
    c, s = math.cos(math.radians(a)), math.sin(math.radians(a)); return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])
def rot_x(a):
    c, s = math.cos(math.radians(a)), math.sin(math.radians(a)); return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])
def rot_z(a):
    c, s = math.cos(math.radians(a)), math.sin(math.radians(a)); return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])
def turn(e): return rot_y(e[0]) @ rot_x(e[1]) @ rot_z(e[2])
def angles(R):
    return np.array([math.degrees(math.atan2(R[0, 2], R[2, 2])), math.degrees(math.asin(max(-1, min(1, -R[1, 2])))),
                     math.degrees(math.atan2(R[1, 0], R[1, 1]))])
# RSQ_HandTable order (AE handtable.zs) and each gun's ready key
ORDER = [('Knife_3D', 1, None), ('M240Flamethrower_3D', 2, ('FLMT', 'A')), ('M4A3Pistol_3D', 3, ('MM91', 'A')), ('MercPistol_3D', 4, ('MM91', 'A')),
         ('NewShotgun_3D', 5, ('ATSG', 'A')), ('PulseRifle_3D', 6, ('PULS', 'A')), ('Satcheler_3D', 7, None), ('Smartgun_3D', 8, ('SMRT', 'A')),
         ('SynthPistol_3D', 9, ('MM91', 'A')), ('YutaniFlamer_3D', 10, ('YLAM', 'A')), ('YutaniKnife_3D', 11, None), ('YutaniPistol_3D', 12, ('YM91', 'A')),
         ('YutaniRifle_3D', 13, ('YULS', 'A')), ('YutaniSatchel_3D', 14, None), ('YutaniShotgun_3D', 15, ('YTSG', 'A')), ('YutaniSmartgun_3D', 16, ('YMRT', 'A'))]
def build(AE):
    blocks = []
    for f in sorted(glob.glob(AE + '/modeldef.*.txt')):
        blocks += km.modeldef_blocks(open(f, encoding='latin-1').read())
    guns, rows, report = [], [], []
    for cls, idx, rk in ORDER:
        mine = [b for b in blocks if b['cls'].lower() == cls.lower()]
        first = next((b for b in mine if rk and rk in b['keys']), None)
        if not first:
            guns.append((idx, cls, np.zeros(3), False, False)); report.append('%s: no gun block, left out' % cls); continue
        keys, nointerp = {}, {}
        for b in mine:
            if b['mesh'].lower() == first['mesh'].lower() and b['path'].lower() == first['path'].lower():
                for k, f in b['keys'].items():
                    keys.setdefault(k, f); nointerp.setdefault(k, b['nointerp'])
        xs, ys, zs = first['scale']; xo, yo, zo = first['off']
        pivot = D @ np.array([xo, zo, yo]) - O_H
        mirrored = xs > 0
        blends = not nointerp.get(rk, first['nointerp'])
        guns.append((idx, cls, pivot, mirrored, blends))
        path = km.find_file(AE, first['path'].replace('\\', '/') + '/' + first['mesh'])
        get, nfr = km.md3_frames(path)
        rf = keys[rk]
        a = km.to_ctrl(get(rf), first)
        cache, n = {}, 0
        for (spr, fr), f in sorted(keys.items(), key=lambda kv: (kv[0][0], kv[0][1])):
            if f == rf or f >= nfr: continue
            if f not in cache:
                b = km.to_ctrl(get(f), first)
                Rw, tw, err = km.rigid(a, b)
                d = np.linalg.norm(a @ Rw.T + tw - a, axis=1)
                cache[f] = (Rw, tw, float(np.percentile(d, 95)), km.angle_of(Rw), err)
            Rw, tw, move95, ang, err = cache[f]
            if move95 < MIN_MOVE and ang < MIN_TURN: continue
            Rk = D @ Rw @ D
            bk = Rk @ O_H - O_H + D @ tw
            u = Rk.T @ bk
            rows.append(dict(gun=idx, cls=cls, spr=spr, fr=ord(fr) - ord('A'), frl=fr, turn=angles(Rk), move=u, f=f, move95=move95, ang=ang, err=err)); n += 1
        report.append('%-22s pivot %s mirrored %d blends %d  %d keyed, %d move the gun' % (cls, np.round(pivot, 2), mirrored, blends, len(keys), n))
    return guns, rows, report
def emit(guns, rows, out):
    n = max(g[0] for g in guns)
    piv = [np.zeros(3)] * (n + 1); mir = [0] * (n + 1); ble = [0] * (n + 1)
    for idx, cls, pivot, mirrored, blends in guns:
        piv[idx] = pivot; mir[idx] = int(mirrored); ble[idx] = int(blends)
    L = ['// generated by ae_gunmoves_gen.py (the kit\'s rsq_gunmoves_gen.py maths, for the Aliens set) -- do not edit by hand',
         '// How each gun\'s model moves under the gun hand and the support hand (rsq/hands.zs keeps',
         '// both on it). Indexed like RSQ_HandTable. Units are ModifyBobLayer3D\'s in the hand models\'',
         '// frame: centimetres, x left, y up, z back; angles yaw about y, pitch about x, roll about z.',
         '// Every keyed frame of the gun\'s own mesh that moves the body is listed: the fire kick, the',
         '// shotgun\'s pump, and the set\'s own reload swings, so the hands ride the gun through all of them.',
         '', 'class RSQ_GunMoves abstract play', '{']
    L += ['\t// where the gun model turns when its layer is offset (raise, lower, a kick by Offset),', '\t// from where the hand models turn',
          '\tclearscope static Vector3 Pivot(int i)', '\t{']
    L.append('\t\tstatic const double v[] = { %s };' % ', '.join('%.3f, %.3f, %.3f' % tuple(p) for p in piv))
    L += ['\t\tif (i <= 0 || 3 * i + 2 >= v.Size())', '\t\t\treturn (0, 0, 0);', '\t\treturn (v[3 * i], v[3 * i + 1], v[3 * i + 2]);', '\t}', '']
    L += ['\t// the gun model is mirrored left-right against the hands (its Scale x is positive)', '\tclearscope static bool Mirrored(int i)', '\t{',
          '\t\tstatic const int v[] = { %s };' % ', '.join(str(x) for x in mir), '\t\treturn i > 0 && i < v.Size() && v[i] != 0;', '\t}', '']
    L += ['\t// the engine blends this gun\'s model frames from one state to the next (no NoInterpolation)', '\tclearscope static bool Blends(int i)', '\t{',
          '\t\tstatic const int v[] = { %s };' % ', '.join(str(x) for x in ble), '\t\treturn i > 0 && i < v.Size() && v[i] != 0;', '\t}', '']
    moves, mindex, groups = [], {}, {}
    for r in rows:
        mk = (r['gun'], r['f'])
        if mk not in mindex:
            mindex[mk] = len(moves); moves.append(r)
        groups.setdefault((r['gun'], r['spr'], mindex[mk]), []).append(r['frl'])
    def num(v):
        t = '%.2f' % v; return '0.00' if t == '-0.00' else t
    L += ['\t// how the model frame shown for (sprite, frame) has turned and moved the gun off its ready',
          '\t// frame: the turn, and the move in the turned frame. key: gun, row in v; spr: the sprite, then',
          '\t// its frames that show that row; v: turn x y z, move x y z. (One table of each kind: the VM',
          '\t// gets a function\'s constant tables wrong past 255 entries of one kind.)',
          '\tstatic Vector3, Vector3 Frame(int i, int sprite, int frame)', '\t{']
    gk = sorted(groups)
    L.append('\t\tstatic const int key[] = { %s };' % ', '.join('%d, %d' % (g[0], g[2]) for g in gk))
    L.append('\t\tstatic const String spr[] = { %s };' % ', '.join('"%s%s"' % (g[1], ''.join(sorted(set(groups[g])))) for g in gk))
    L.append('\t\tstatic const double v[] = {')
    for m in moves: L.append('\t\t\t%s,' % ', '.join(num(x) for x in list(m['turn']) + list(m['move'])))
    L[-1] = L[-1].rstrip(','); L.append('\t\t};')
    L += ['\t\tString f = String.Format("%c", 65 + frame);', '\t\tfor (int k = 0; k < spr.Size(); k++)', '\t\t{',
          '\t\t\tif (key[2 * k] == i && spr[k].IndexOf(f, 4) >= 0 && Actor.GetSpriteIndex(spr[k].Left(4)) == sprite)',
          '\t\t\t{', '\t\t\t\tint b = key[2 * k + 1] * 6;', '\t\t\t\treturn (v[b], v[b + 1], v[b + 2]), (v[b + 3], v[b + 4], v[b + 5]);', '\t\t\t}', '\t\t}',
          '\t\treturn (0, 0, 0), (0, 0, 0);', '\t}', '}', '']
    open(out, 'w').write('\n'.join(L))
    print('rows', len(rows), 'moves', len(moves), 'groups', len(gk), '-> v entries', len(moves) * 6)
if __name__ == '__main__':
    guns, rows, report = build(sys.argv[1])
    for l in report: print(l)
    emit(guns, rows, sys.argv[2])
